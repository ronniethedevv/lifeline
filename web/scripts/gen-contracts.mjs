/**
 * Generates typed ABIs and addresses for the web app from the single sources of truth:
 * Foundry's `contracts/out/` (ABIs) and `deployments/testnet.json` (addresses).
 * Never hand-type ABIs or addresses (code_standards.md). Run `forge build` in contracts/ first.
 *
 *   node scripts/gen-contracts.mjs          write lib/generated/{abis,addresses}.ts
 *   node scripts/gen-contracts.mjs --check  exit 1 if they are out of date
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(new URL("../../contracts/out/", import.meta.url));
const DEPLOYMENTS = fileURLToPath(new URL("../../deployments/testnet.json", import.meta.url));
const GEN_DIR = fileURLToPath(new URL("../lib/generated/", import.meta.url));
const ABIS_FILE = `${GEN_DIR}abis.ts`;
const ADDRESSES_FILE = `${GEN_DIR}addresses.ts`;

/** [export name, source file in out/, contract name] */
const ABIS = [
  ["vaultFactoryAbi", "VaultFactory.sol", "VaultFactory"],
  ["positionVaultAbi", "PositionVault.sol", "PositionVault"],
  ["rescueMarketAbi", "RescueMarket.sol", "RescueMarket"],
  ["minimalFeePricerAbi", "MinimalFeePricer.sol", "MinimalFeePricer"],
  ["fuzzyFeePricerAbi", "FuzzyFeePricer.sol", "FuzzyFeePricer"],
  ["borrowerOperationsAbi", "IBorrowerOperations.sol", "IBorrowerOperations"],
  ["troveManagerAbi", "ITroveManager.sol", "ITroveManager"],
  ["priceFeedAbi", "IPriceFeed.sol", "IPriceFeed"],
  ["hintHelpersAbi", "IHintHelpers.sol", "IHintHelpers"],
  ["sortedTrovesAbi", "ISortedTroves.sol", "ISortedTroves"],
  ["erc20Abi", "IERC20.sol", "IERC20"],
];

const HEADER = "// GENERATED by scripts/gen-contracts.mjs. Do not edit; run `pnpm gen:contracts`.\n";

function abiOf(file, name) {
  return JSON.parse(readFileSync(`${OUT}${file}/${name}.json`, "utf8")).abi;
}

function generateAbis() {
  const parts = ABIS.map(
    ([exportName, file, name]) => `export const ${exportName} = ${JSON.stringify(abiOf(file, name), null, 2)} as const;\n`,
  );
  return HEADER + "\n" + parts.join("\n");
}

function generateAddresses() {
  const d = JSON.parse(readFileSync(DEPLOYMENTS, "utf8"));
  const addresses = {
    vaultFactory: d.lifeline.VaultFactory.address,
    rescueMarket: d.lifeline.RescueMarket.address,
    minimalFeePricer: d.lifeline.MinimalFeePricer.address,
    fuzzyFeePricer: d.lifeline.FuzzyFeePricer.address,
    borrowerOperations: d.musd.BorrowerOperations.address,
    troveManager: d.musd.TroveManager.address,
    priceFeed: d.musd.PriceFeed.address,
    hintHelpers: d.musd.HintHelpers.address,
    sortedTroves: d.musd.SortedTroves.address,
    musd: d.musd.MUSD.address,
  };
  return (
    HEADER +
    "\nimport type { Address } from \"viem\";\n\n" +
    `export const CHAIN_ID = ${d.chainId} as const;\n` +
    `export const RPC_URL = ${JSON.stringify(d.rpc)} as const;\n\n` +
    `export const addresses = ${JSON.stringify(addresses, null, 2)} as const satisfies Record<string, Address>;\n`
  );
}

function main() {
  const targets = [
    [ABIS_FILE, generateAbis()],
    [ADDRESSES_FILE, generateAddresses()],
  ];
  if (process.argv.includes("--check")) {
    const stale = targets.filter(([path, content]) => readFileSync(path, "utf8") !== content).map(([p]) => p);
    if (stale.length > 0) {
      console.error(`Generated contracts are stale: ${stale.join(", ")}. Run \`pnpm gen:contracts\`.`);
      process.exit(1);
    }
    return;
  }
  mkdirSync(GEN_DIR, { recursive: true });
  for (const [path, content] of targets) writeFileSync(path, content);
  console.log(`Wrote ${ABIS_FILE} and ${ADDRESSES_FILE}`);
}

main();
